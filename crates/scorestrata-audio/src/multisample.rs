//! Multi-sample instrument engine (Phase G) — SFZ-style sample playback.
//!
//! # Why samples
//!
//! The subtractive voice (`SynthParams`) is the only melodic voice in the
//! engine, so "rock" layers render as saw/square oscillators with drive — a
//! distorted synth, not a guitar (see `docs/planning/
//! real-instrument-synthesis-investigation.md` §1). A **multi-sample
//! instrument** plays recorded (or deterministically generated) one-shots
//! per key range and velocity layer, which is how real samplers get a
//! plucked string to sound like a plucked string.
//!
//! # Model (the SFZ subset the plan's §1.4 named)
//!
//! - **Key zones**: a sample covers `key_min..=key_max`; the closest root
//!   note is pitch-shifted to the played pitch.
//! - **Velocity layers**: `vel_min..=vel_max` per zone; the played velocity
//!   selects the layer (soft pick vs hard pick).
//! - **Round robins**: several samples per zone; the deterministic RR picker
//!   cycles per note so repeated hits don't machine-gun.
//! - **Loop points**: `loop_start`/`loop_end` sustain a tone instead of
//!   decaying (e-piano / pads).
//!
//! # Determinism (R1/R2)
//!
//! Playback is a phase-accumulator with linear interpolation — a pure
//! function of `(sample, pitch, velocity, rr_seed)`, no hidden state, so
//! identical inputs produce identical bytes. Load-time rate conversion uses
//! rubato's FFT resampler (latency-free, offline, deterministic).
//!
//! # Assets
//!
//! The bank ships embedded WAV one-shots (`include_bytes!`) generated by
//! `src/bin/gen_instrument_bank.rs` (pure parametric synthesis — plucked
//! string, FM e-piano — so the crate keeps its zero-external-asset posture,
//! R7). The loader is asset-agnostic: drop any 44.1/48 kHz mono WAV set
//! into the same zone manifest and it plays.

// Sample playback uses bounded f32/usize and u64 casts (phase-accumulator
// indexing); sample lengths fit practical ranges on all targets.
#![expect(
    clippy::cast_possible_truncation,
    clippy::cast_precision_loss,
    clippy::cast_sign_loss,
    reason = "Phase-accumulator playback casts bounded sample indexes and lengths; buffers fit practical ranges"
)]

use std::collections::HashMap;

use crate::error::AudioError;

/// A single one-shot sample (mono, floating point, [-1, 1]).
#[derive(Debug, Clone)]
pub struct Sample {
    /// MIDI root note the sample was recorded at.
    pub root_note: u8,
    /// Samples at the bank's native rate.
    pub data: Vec<f32>,
    /// Sample rate of `data` (usually the bank rate).
    pub sample_rate: u32,
    /// Optional sustain loop (sample-index range, `None` = one-shot decay).
    pub loop_start: Option<usize>,
    /// Optional sustain loop end (`None` = loop to end).
    pub loop_end: Option<usize>,
}

/// A playable key zone with one or more round-robin samples.
#[derive(Debug, Clone)]
pub struct SampleZone {
    /// Inclusive key range this zone covers.
    pub key_min: u8,
    /// Inclusive key range this zone covers.
    pub key_max: u8,
    /// Inclusive velocity range (0.0–1.0) this zone covers.
    pub vel_min: f32,
    /// Inclusive velocity range (0.0–1.0) this zone covers.
    pub vel_max: f32,
    /// Round-robin alternates for this zone.
    pub samples: Vec<Sample>,
}

impl SampleZone {
    /// Does this zone cover the given key and velocity?
    fn covers(&self, pitch: u8, velocity: f32) -> bool {
        pitch >= self.key_min
            && pitch <= self.key_max
            && velocity >= self.vel_min
            && velocity <= self.vel_max
    }

    /// Deterministically pick the round-robin sample for a hit.
    ///
    /// `rr_seed` is a per-note hash (pitch ⊕ velocity bits ⊕ start tick) so
    /// repeated identical hits still cycle (R2) while staying byte-exact.
    fn pick(&self, rr_seed: u64) -> &Sample {
        let idx = (rr_seed % self.samples.len().max(1) as u64) as usize;
        &self.samples[idx]
    }
}

/// A named multi-sample instrument.
#[derive(Debug, Clone, Default)]
pub struct MultiSampleInstrument {
    /// Instrument name (matches `Layer.instrument` suffixes, e.g. `guitar`).
    pub name: String,
    /// Key/velocity zones, sorted for linear scan.
    pub zones: Vec<SampleZone>,
}

impl MultiSampleInstrument {
    /// Find the first zone covering the hit.
    fn zone_for(&self, pitch: u8, velocity: f32) -> Option<&SampleZone> {
        self.zones
            .iter()
            .find(|z| z.covers(pitch, velocity.clamp(0.0, 1.0)))
    }

    /// Render one note into `output` (additive mix, like the drum sampler).
    ///
    /// Selects the zone, pitch-shifts the round-robin sample with a
    /// phase-accumulator + linear interpolation, applies the velocity gain,
    /// and loops the sustain region if the note outlives the sample.
    pub fn render_note(&self, pitch: u8, velocity: f32, rr_seed: u64, output: &mut [f32]) {
        let Some(zone) = self.zone_for(pitch, velocity) else {
            return;
        };
        let sample = zone.pick(rr_seed);
        let gain = velocity.clamp(0.0, 1.0);
        let ratio = ((f32::from(pitch) - f32::from(sample.root_note)) / 12.0).exp2();

        // Phase accumulator: source position advances by `ratio` per output
        // sample. Linear interpolation between source frames.
        let mut pos = 0.0f32;
        let loop_start = sample.loop_start.unwrap_or(0) as f32;
        let loop_end = sample
            .loop_end
            .unwrap_or_else(|| sample.data.len().saturating_sub(1))
            .max(loop_start as usize + 1) as f32;
        let looping = sample.loop_start.is_some();
        let src_len = sample.data.len() as f32;

        for out in output.iter_mut() {
            if pos >= src_len {
                if looping {
                    pos = loop_start;
                } else {
                    break;
                }
            }
            let i0 = pos.floor() as usize;
            let i1 = (i0 + 1).min(sample.data.len().saturating_sub(1));
            let frac = pos - i0 as f32;
            let value = sample.data[i0].mul_add(1.0 - frac, sample.data[i1] * frac);
            *out = value.mul_add(gain, *out);
            pos += ratio;
            if looping && pos >= loop_end {
                pos = loop_start + ((pos - loop_end) % (loop_end - loop_start));
            }
        }
    }
}

/// The instrument bank: name → multi-sample instrument.
#[derive(Debug, Clone, Default)]
pub struct InstrumentBank {
    instruments: HashMap<String, MultiSampleInstrument>,
}

impl InstrumentBank {
    /// Create an empty bank.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Register (or replace) an instrument.
    pub fn register(&mut self, instrument: MultiSampleInstrument) {
        self.instruments.insert(instrument.name.clone(), instrument);
    }

    /// Look up an instrument by name.
    #[must_use]
    pub fn get(&self, name: &str) -> Option<&MultiSampleInstrument> {
        self.instruments.get(name)
    }

    /// Mutable lookup (for building banks by merging zones).
    pub fn get_mut(&mut self, name: &str) -> Option<&mut MultiSampleInstrument> {
        self.instruments.get_mut(name)
    }

    /// Names of all registered instruments (sorted for stable output).
    #[must_use]
    pub fn names(&self) -> Vec<String> {
        let mut names: Vec<String> = self.instruments.keys().cloned().collect();
        names.sort();
        names
    }

    /// Is an instrument available?
    #[must_use]
    pub fn has(&self, name: &str) -> bool {
        self.instruments.contains_key(name)
    }

    /// Render a named instrument's note into `output`.
    pub fn render_note(
        &self,
        name: &str,
        pitch: u8,
        velocity: f32,
        rr_seed: u64,
        output: &mut [f32],
    ) -> bool {
        let Some(instrument) = self.instruments.get(name) else {
            return false;
        };
        instrument.render_note(pitch, velocity, rr_seed, output);
        true
    }

    /// Load a mono WAV one-shot from raw bytes at the given MIDI root note
    /// and register it as a single zone under `instrument`.
    ///
    /// The WAV's native rate is converted to `target_rate` with rubato's
    /// offline FFT resampler (latency-free, deterministic). Any hound-readable
    /// PCM/float WAV works, so real CC0 libraries can be dropped in.
    ///
    /// # Errors
    ///
    /// Returns [`AudioError::InvalidWav`] if `wav_bytes` is not a parseable
    /// WAV in a supported encoding.
    #[expect(
        clippy::too_many_arguments,
        reason = "A zone load is one flat descriptor: instrument, root, key/vel bounds, bytes, rate"
    )]
    pub fn load_zone_from_wav(
        &mut self,
        instrument: &str,
        root_note: u8,
        key_min: u8,
        key_max: u8,
        vel_min: f32,
        vel_max: f32,
        wav_bytes: &[u8],
        target_rate: u32,
    ) -> Result<(), AudioError> {
        let (data, rate) = crate::wav::read_wav_mono(wav_bytes)?;
        let data = crate::wav::convert_rate(&data, rate, target_rate);
        let sample = Sample {
            root_note,
            data,
            sample_rate: target_rate,
            loop_start: None,
            loop_end: None,
        };
        let zone = SampleZone {
            key_min,
            key_max,
            vel_min,
            vel_max,
            samples: vec![sample],
        };
        self.instruments
            .entry(instrument.to_string())
            .or_insert_with(|| MultiSampleInstrument {
                name: instrument.to_string(),
                zones: Vec::new(),
            })
            .zones
            .push(zone);
        Ok(())
    }

    /// Total sample frames across all instruments (diagnostic).
    #[must_use]
    pub fn total_frames(&self) -> usize {
        self.instruments
            .values()
            .flat_map(|i| &i.zones)
            .flat_map(|z| &z.samples)
            .map(|s| s.data.len())
            .sum()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 440 Hz sine at 48 kHz, 1 second.
    fn sine_440(rate: u32) -> Vec<f32> {
        let n = rate as usize;
        (0..n)
            .map(|i| (std::f32::consts::TAU * 440.0 * i as f32 / rate as f32).sin() * 0.5)
            .collect()
    }

    fn bank_with_guitar() -> InstrumentBank {
        let mut bank = InstrumentBank::new();
        let mut inst = MultiSampleInstrument {
            name: "guitar".to_string(),
            zones: vec![SampleZone {
                key_min: 40,
                key_max: 72,
                vel_min: 0.0,
                vel_max: 1.0,
                samples: vec![Sample {
                    root_note: 57,
                    data: sine_440(48_000),
                    sample_rate: 48_000,
                    loop_start: None,
                    loop_end: None,
                }],
            }],
        };
        // Second round-robin alternate for the determinism test.
        inst.zones[0].samples.push(Sample {
            root_note: 57,
            data: sine_440(48_000).iter().map(|s| s * 0.9).collect(),
            sample_rate: 48_000,
            loop_start: None,
            loop_end: None,
        });
        bank.register(inst);
        bank
    }

    #[test]
    fn zone_selection_respects_key_and_velocity_ranges() {
        let inst = MultiSampleInstrument {
            name: "guitar".to_string(),
            zones: vec![
                SampleZone {
                    key_min: 40,
                    key_max: 60,
                    vel_min: 0.0,
                    vel_max: 0.5,
                    samples: vec![Sample {
                        root_note: 48,
                        data: vec![1.0; 100],
                        sample_rate: 48_000,
                        loop_start: None,
                        loop_end: None,
                    }],
                },
                SampleZone {
                    key_min: 40,
                    key_max: 60,
                    vel_min: 0.5,
                    vel_max: 1.0,
                    samples: vec![Sample {
                        root_note: 48,
                        data: vec![2.0; 100],
                        sample_rate: 48_000,
                        loop_start: None,
                        loop_end: None,
                    }],
                },
            ],
        };
        // Hard hit picks the loud layer.
        let mut out = vec![0.0; 10];
        inst.render_note(48, 0.9, 0, &mut out);
        assert!(out.iter().all(|s| (s - 1.8).abs() < 1e-4), "loud layer");
        // Soft hit picks the quiet layer (sample 1.0 × velocity 0.2).
        let mut out = vec![0.0; 10];
        inst.render_note(48, 0.2, 0, &mut out);
        assert!(out.iter().all(|s| (s - 0.2).abs() < 1e-4), "soft layer");
        // Out-of-range key renders nothing.
        let mut out = vec![0.0; 10];
        inst.render_note(80, 0.9, 0, &mut out);
        assert!(out.iter().all(|s| *s == 0.0), "no zone");
    }

    #[test]
    fn pitch_shift_plays_at_the_played_frequency() {
        let bank = bank_with_guitar();
        let sample_rate = 48_000u32;
        let n = (sample_rate as usize) / 2; // 0.5 s
        let mut out = vec![0.0; n];

        // Play A3 (57) — root note, no shift: 440 Hz.
        bank.render_note("guitar", 57, 1.0, 0, &mut out);
        let mut crossings = 0;
        for w in out.windows(2) {
            if (w[0] >= 0.0) != (w[1] >= 0.0) {
                crossings += 1;
            }
        }
        let hz = crossings as f32 / 2.0 / (n as f32 / sample_rate as f32);
        assert!(
            (hz - 440.0).abs() < 15.0,
            "root note plays ~440 Hz (got {hz:.1})"
        );

        // Play A4 (69) — one octave up: ~880 Hz.
        let mut out = vec![0.0; n];
        bank.render_note("guitar", 69, 1.0, 0, &mut out);
        let mut crossings = 0;
        for w in out.windows(2) {
            if (w[0] >= 0.0) != (w[1] >= 0.0) {
                crossings += 1;
            }
        }
        let hz = crossings as f32 / 2.0 / (n as f32 / sample_rate as f32);
        assert!(
            (hz - 880.0).abs() < 30.0,
            "octave-up plays ~880 Hz (got {hz:.1})"
        );
    }

    #[test]
    fn round_robin_alternates_deterministically_by_seed() {
        let bank = bank_with_guitar();
        let mut a = vec![0.0; 8];
        let mut b = vec![0.0; 8];
        bank.render_note("guitar", 57, 1.0, 0, &mut a);
        bank.render_note("guitar", 57, 1.0, 0, &mut b);
        assert_eq!(a, b, "same seed → same bytes (R2)");

        let mut c = vec![0.0; 8];
        bank.render_note("guitar", 57, 1.0, 1, &mut c);
        assert_ne!(a, c, "different seed → different alternate");
    }

    #[test]
    fn looping_sustains_beyond_sample_length() {
        let mut inst = MultiSampleInstrument {
            name: "pad".to_string(),
            zones: vec![SampleZone {
                key_min: 40,
                key_max: 80,
                vel_min: 0.0,
                vel_max: 1.0,
                samples: vec![Sample {
                    root_note: 60,
                    // 100-sample loop of a constant tone.
                    data: vec![0.5; 100],
                    sample_rate: 48_000,
                    loop_start: Some(0),
                    loop_end: Some(100),
                }],
            }],
        };
        let _ = &mut inst;
        let mut bank = InstrumentBank::new();
        bank.register(inst);
        let mut out = vec![0.0; 10_000];
        bank.render_note("pad", 60, 1.0, 0, &mut out);
        // Loop sustains for the whole note: no trailing silence.
        assert!(
            out[out.len() - 1].abs() > 0.4,
            "loop sustains (last = {})",
            out[out.len() - 1]
        );
    }

    #[test]
    fn unknown_instrument_returns_false() {
        let bank = bank_with_guitar();
        let mut out = vec![0.0; 8];
        assert!(!bank.render_note("does_not_exist", 60, 1.0, 0, &mut out));
    }
}
